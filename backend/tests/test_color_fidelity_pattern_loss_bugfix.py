@st.composite
def patterned_garment_strategy(draw):
    """
    Generate garment images with patterns/multiple colors.

    Scoped to garments with pattern_score > 0.3 OR color_variance > 30
    """
    # Choose pattern type
    pattern_type = draw(
        st.sampled_from(
            [
                "checkerboard",
                "stripes",
                "stars",
                "cartoon",
                "embroidery",
            ]
        )
    )

    # Choose size (typical garment image sizes)
    width = draw(st.integers(min_value=256, max_value=768))
    height = draw(st.integers(min_value=256, max_value=768))

    # Choose colors (at least 2 colors for patterns)
    num_colors = draw(st.integers(min_value=2, max_value=5))
    colors = []
    for _ in range(num_colors):
        r = draw(st.integers(min_value=50, max_value=255))
        g = draw(st.integers(min_value=50, max_value=255))
        b = draw(st.integers(min_value=50, max_value=255))
        colors.append((r, g, b))

    # Generate the garment image
    garment = make_patterned_garment((width, height), pattern_type, colors)

    # Verify it meets the scoping criteria
    pattern_score = calculate_pattern_score(garment)
    color_variance = calculate_color_variance(garment)

    # Only return if it meets the bug condition criteria
    if pattern_score > 0.3 or color_variance > 30:
        return {
            "garment": garment,
            "pattern_type": pattern_type,
            "pattern_score": pattern_score,
            "color_variance": color_variance,
        }
    else:
        # Reject and retry
        # This shouldn't happen often with our generator, but just in case
        return draw(patterned_garment_strategy())


def make_simple_person_image(size: tuple[int, int] = (512, 768)) -> Image.Image:
    """Create a simple person-like image for testing."""
    width, height = size
    arr = np.zeros((height, width, 3), dtype=np.uint8)

    # Background
    arr[:, :] = (200, 200, 200)

    # Simple person silhouette (rectangle for body)
    body_left = width // 3
    body_right = 2 * width // 3
    body_top = height // 4
    body_bottom = 3 * height // 4

    # Skin tone for body
    arr[body_top:body_bottom, body_left:body_right] = (220, 180, 150)

    return Image.fromarray(arr, mode="RGB")


def make_simple_catvton_result(size: tuple[int, int] = (512, 768)) -> Image.Image:
    """Create a simple CatVTON result image for testing."""
    width, height = size
    arr = np.zeros((height, width, 3), dtype=np.uint8)

    # Background
    arr[:, :] = (180, 180, 180)

    # Person with garment area (slightly different color)
    body_left = width // 3
    body_right = 2 * width // 3
    body_top = height // 4
    body_bottom = 3 * height // 4

    # Garment area (gray - this is what should be replaced with pattern)
    arr[body_top:body_bottom, body_left:body_right] = (150, 150, 150)

    return Image.fromarray(arr, mode="RGB")


