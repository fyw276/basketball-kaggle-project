def make_patterned_garment(
    size: tuple[int, int],
    pattern_type: str,
    colors: list[tuple[int, int, int]],
) -> Image.Image:
    """
    Generate a garment image with obvious patterns.

    Args:
        size: (width, height) of the image
        pattern_type: "checkerboard", "stripes", "stars", "cartoon", "embroidery"
        colors: List of RGB tuples to use in the pattern

    Returns:
        PIL Image with the specified pattern
    """
    width, height = size
    arr = np.zeros((height, width, 3), dtype=np.uint8)

    if pattern_type == "checkerboard":
        # Create checkerboard pattern
        square_size = max(8, min(width, height) // 16)
        for y in range(height):
            for x in range(width):
                sx = (x // square_size) % len(colors)
                sy = (y // square_size) % len(colors)
                color_idx = (sx + sy) % len(colors)
                arr[y, x] = colors[color_idx]

    elif pattern_type == "stripes":
        # Create horizontal stripes
        stripe_height = max(8, height // 10)
        for y in range(height):
            color_idx = (y // stripe_height) % len(colors)
            arr[y, :] = colors[color_idx]

    elif pattern_type == "stars":
        # Create colorful stars on a base color
        base_color = colors[0]
        arr[:, :] = base_color

        # Add star-like patterns (simplified as circles)
        num_stars = 15
        for i in range(num_stars):
            # Deterministic star positions based on index
            cx = (i * 137) % width  # Use prime number for distribution
            cy = (i * 211) % height
            radius = max(10, min(width, height) // 20)
            star_color = colors[(i % (len(colors) - 1)) + 1]

            # Draw circle
            for y in range(max(0, cy - radius), min(height, cy + radius)):
                for x in range(max(0, cx - radius), min(width, cx + radius)):
                    if (x - cx) ** 2 + (y - cy) ** 2 <= radius**2:
                        arr[y, x] = star_color

    elif pattern_type == "cartoon":
        # Create cartoon-like pattern with bold colors
        base_color = colors[0]
        arr[:, :] = base_color

        # Add cartoon character-like shapes (simplified as rectangles and circles)
        # Head (circle)
        head_cx = width // 2
        head_cy = height // 3
        head_radius = min(width, height) // 6
        head_color = colors[1] if len(colors) > 1 else (255, 200, 150)

        for y in range(max(0, head_cy - head_radius), min(height, head_cy + head_radius)):
            for x in range(max(0, head_cx - head_radius), min(width, head_cx + head_radius)):
                if (x - head_cx) ** 2 + (y - head_cy) ** 2 <= head_radius**2:
                    arr[y, x] = head_color

        # Body (rectangle)
        body_color = colors[2] if len(colors) > 2 else (100, 150, 255)
        body_top = head_cy + head_radius
        body_bottom = min(height, body_top + height // 3)
        body_left = head_cx - head_radius // 2
        body_right = head_cx + head_radius // 2
        arr[body_top:body_bottom, body_left:body_right] = body_color

    elif pattern_type == "embroidery":
        # Create embroidery-like pattern with fine details
        base_color = colors[0]
        arr[:, :] = base_color

        # Add embroidery-like lines and dots
        embroidery_color = colors[1] if len(colors) > 1 else (200, 50, 50)

        # Vertical lines
        for x in range(width // 4, width, width // 8):
            if x < width:
                arr[:, x : min(x + 2, width)] = embroidery_color

        # Horizontal lines
        for y in range(height // 4, height, height // 8):
            if y < height:
                arr[y : min(y + 2, height), :] = embroidery_color

        # Dots at intersections
        for y in range(height // 4, height, height // 8):
            for x in range(width // 4, width, width // 8):
                if y < height and x < width:
                    dot_radius = 3
                    for dy in range(-dot_radius, dot_radius + 1):
                        for dx in range(-dot_radius, dot_radius + 1):
                            if (
                                dx**2 + dy**2 <= dot_radius**2
                                and 0 <= y + dy < height
                                and 0 <= x + dx < width
                            ):
                                arr[y + dy, x + dx] = (
                                    colors[2] if len(colors) > 2 else (255, 200, 50)
                                )

    return Image.fromarray(arr, mode="RGB")


def calculate_rgb_mean_non_transparent(image: Image.Image, alpha_threshold: int = 128) -> float:
    """
    Calculate the mean RGB value in non-transparent regions of an RGBA image.

    Args:
        image: PIL Image in RGBA mode
        alpha_threshold: Minimum alpha value to consider a pixel non-transparent

    Returns:
        Mean RGB value across all non-transparent pixels
    """
    if image.mode != "RGBA":
        image = image.convert("RGBA")

    arr = np.array(image, dtype=np.float32)
    alpha = arr[:, :, 3]

    # Find non-transparent pixels
    non_transparent_mask = alpha > alpha_threshold

    if not non_transparent_mask.any():
        # No non-transparent pixels, return 0
        return 0.0

    # Calculate mean RGB in non-transparent regions
    rgb_values = arr[:, :, :3][non_transparent_mask]
    return float(rgb_values.mean())


def calculate_pattern_score(image: Image.Image) -> float:
    """
    Calculate a pattern score for the image based on color variance.

    Returns:
        Pattern score between 0 and 1 (higher = more patterned)
    """
    import cv2

    arr = np.array(image.convert("RGB"))
    hsv = cv2.cvtColor(arr, cv2.COLOR_RGB2HSV).astype(np.float32)
    sat = hsv[:, :, 1]

    # Calculate saturation variance as a proxy for pattern complexity
    sat_std = float(sat.std())
    # Normalize to 0-1 range (empirically, std > 30 indicates patterns)
    pattern_score = min(1.0, sat_std / 50.0)

    return pattern_score


def calculate_color_variance(image: Image.Image) -> float:
    """
    Calculate color variance in the image.

    Returns:
        Color variance (higher = more color variation)
    """
    arr = np.array(image.convert("RGB"), dtype=np.float32)

    # Calculate variance across all RGB channels
    r_var = float(arr[:, :, 0].var())
    g_var = float(arr[:, :, 1].var())
    b_var = float(arr[:, :, 2].var())

    # Return average variance
    return (r_var + g_var + b_var) / 3.0


