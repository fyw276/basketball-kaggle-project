@settings(
    max_examples=3,
    deadline=None,
    suppress_health_check=[HealthCheck.function_scoped_fixture, HealthCheck.too_slow],
)
@given(garment_data=patterned_garment_strategy())
def test_bug_condition_warped_layer_preserves_color_information(garment_data: dict):
    """
    **Property 1: Bug Condition - Warped Layer Preserves Color Information**

    **Validates: Requirements 2.1, 2.2, 2.3, 2.4**

    For any garment image with patterns or multiple colors (pattern_score > 0.3 OR
    color_variance > 30), the warped_layer generated by catvton_color_fidelity_spatial
    SHALL influence the result such that:

    1. The result RGB mean in the garment region is > 20.0 (not nearly black)
    2. The result differs from catvton_result in the garment region (warped_layer has influence)
    3. The result's color variance (pattern) is preserved, not collapsed to uniform gray

    **CRITICAL**: This test is EXPECTED TO FAIL on unfixed code.
    Failure confirms the bug exists (warped_layer has no influence on result).

    **NOTE**: The blending formula is:
    result = warped_layer * alpha * strength + catvton * (1 - alpha * strength).
    The result CANNOT equal the original garment color because catvton also contributes.
    Instead, we verify the warped_layer is actually influencing the result.
    """
    from app.services.tryon_v2.warp_engine import catvton_color_fidelity_spatial

    garment = garment_data["garment"]
    pattern_type = garment_data["pattern_type"]
    pattern_score = garment_data["pattern_score"]
    color_variance = garment_data["color_variance"]

    # Create test inputs
    catvton_result = make_simple_catvton_result((512, 768))
    person_image = make_simple_person_image((512, 768))

    # Calculate original garment statistics
    original_color_var = calculate_color_variance(garment)

    # Call the function under test
    result, metadata = catvton_color_fidelity_spatial(
        catvton_result=catvton_result,
        original_garment=garment,
        person_image=person_image,
        garment_category="top",
        fidelity_strength=0.75,
    )

    # Extract garment region from result and catvton_result
    result_arr = np.array(result.convert("RGB"), dtype=np.float32)
    catvton_arr = np.array(catvton_result.convert("RGB"), dtype=np.float32)

    height, width = result_arr.shape[:2]
    # Garment region: middle third width, middle half height
    gr_slice = (slice(height // 4, 3 * height // 4), slice(width // 3, 2 * width // 3))
    garment_region = result_arr[gr_slice]
    catvton_region = catvton_arr[gr_slice]

    result_rgb_mean = float(garment_region.mean())

    # Assertion 1: RGB mean should be > 20.0 (not nearly black)
    assert result_rgb_mean > 20.0, (
        f"Bug detected: Result RGB mean is {result_rgb_mean:.2f} (nearly black) "
        f"for {pattern_type} garment with pattern_score={pattern_score:.3f}, "
        f"color_variance={color_variance:.2f}. "
        f"Expected RGB mean > 20.0 to preserve pattern visibility."
    )

    # Assertion 2: Result should differ from catvton_result in garment region
    # This proves the warped_layer is actually contributing to the result.
    # If warped_layer has zero influence, result == catvton_result.
    catvton_rgb_mean = float(catvton_region.mean())
    diff_from_catvton = abs(result_rgb_mean - catvton_rgb_mean)
    assert diff_from_catvton > 1.0, (
        f"Bug detected: Result RGB mean ({result_rgb_mean:.2f}) is nearly identical to "
        f"catvton_result RGB mean ({catvton_rgb_mean:.2f}), diff={diff_from_catvton:.2f}. "
        f"The warped_layer has no influence on the result. "
        f"Pattern type: {pattern_type}, pattern_score={pattern_score:.3f}."
    )

    # Assertion 3: Result color variance should be > 0 (not uniform gray)
    # If the pattern is lost, the garment region becomes uniform.
    result_var = float(garment_region.reshape(-1, 3).var(axis=0).mean())
    assert result_var > 0.5, (
        f"Bug detected: Result color variance is {result_var:.2f} (nearly uniform). "
        f"Original garment color variance: {original_color_var:.2f}. "
        f"Pattern type: {pattern_type}. The pattern appears to be lost."
    )

    print(
        f"✓ Pattern preserved: {pattern_type} "
        f"(result RGB={result_rgb_mean:.2f}, catvton RGB={catvton_rgb_mean:.2f}, "
        f"diff={diff_from_catvton:.2f}, var={result_var:.2f}, "
        f"pattern_score={pattern_score:.3f}, color_variance={color_variance:.2f})"
    )


